package app

import (
	"net/http"

	api "github.com/kannachi323/misty/server/internal/platform/httpapi"
)

func (s *Server) mountAIRoutes(prefix string, aiService *api.AIService) {
	s.Router.Get(prefix+"/status", aiService.Status())
	s.Router.Get(prefix+"/models", aiService.FrontierModels())
	s.Router.Post(prefix+"/complete", aiService.Complete())
	s.Router.MethodFunc(http.MethodGet, prefix+"/settings", aiService.Settings())
	s.Router.MethodFunc(http.MethodPut, prefix+"/settings", aiService.Settings())
	s.Router.Put(prefix+"/settings/app-actions", aiService.AppActionsSetting())
	s.Router.Put(prefix+"/settings/agent-sites", aiService.AgentSitesSetting())
	s.Router.Put(prefix+"/settings/keep-awake", aiService.KeepAwakeSetting())
	s.Router.Put(prefix+"/settings/screen-location", aiService.ScreenLocationSetting())
	s.Router.Get(prefix+"/memories", aiService.Memories())
	s.Router.Post(prefix+"/me/voice/cleanup", aiService.VoiceCleanup())
	s.Router.Delete(prefix+"/memories/{memoryID}", aiService.Memory())
	s.Router.Put(prefix+"/memories/{memoryID}", aiService.Memory())
	s.Router.MethodFunc(http.MethodPut, prefix+"/preferences/{surfaceID}", aiService.SurfacePreference())
	s.Router.Get(prefix+"/recaps", aiService.Recaps())
	s.Router.Put(prefix+"/recaps/{surfaceID}", aiService.Recap())
	s.Router.Get(prefix+"/agent-methods", aiService.AgentMethods())
	s.Router.Post(prefix+"/agent-methods", aiService.AgentMethods())
	s.Router.Put(prefix+"/agent-methods/{methodID}", aiService.AgentMethods())
	s.Router.Get(prefix+"/workflow-schedules", aiService.UpcomingWorkflowRuns())
	s.Router.Get(prefix+"/workflow-schedules/device-runs", aiService.DeviceScheduledRuns())
	s.Router.Get(prefix+"/inbound-channels", aiService.InboundChannels())
	s.Router.Put(prefix+"/inbound-channels/{channel}", aiService.InboundChannel())
	s.Router.Delete(prefix+"/inbound-channels/{channel}", aiService.InboundChannel())
	s.Router.Post(prefix+"/workflow-schedules/{scheduleID}/device-claim", aiService.ClaimDeviceScheduledRun())
	s.Router.Put(prefix+"/agent-methods/{methodID}/schedule", aiService.WorkflowSchedule())
	s.Router.Delete(prefix+"/agent-methods/{methodID}/schedule", aiService.WorkflowSchedule())
	s.Router.Get(prefix+"/activity", aiService.MistyActivity())
	s.Router.Post(prefix+"/invocations", aiService.CreateInvocation())
	s.Router.Get(prefix+"/invocations/{invocationID}/events", aiService.InvocationEvents())
	s.Router.Get(prefix+"/invocations/{invocationID}/progress", aiService.InvocationProgress())
	s.Router.Get(prefix+"/invocations/{invocationID}/state", aiService.InvocationState())
	s.Router.Post(prefix+"/invocations/{invocationID}/cancel", aiService.CancelInvocation())
	s.Router.Post(prefix+"/invocations/{invocationID}/steering", aiService.SteerInvocation())
	s.Router.Post(prefix+"/invocations/{invocationID}/pause", aiService.PauseInvocation())
	s.Router.Post(prefix+"/invocations/{invocationID}/resume", aiService.ResumeInvocation())
	s.Router.Post(prefix+"/invocations/{invocationID}/feedback", aiService.InvocationFeedback())
	s.Router.Post(prefix+"/artifacts/{artifactID}/decision", aiService.DecideArtifact())
	s.Router.Post(prefix+"/artifacts/{artifactID}/completion", aiService.CompleteArtifact())
	s.Router.Get(prefix+"/conversations", aiService.AIConversations())
	s.Router.Get(prefix+"/conversations/{conversationID}", aiService.AIConversation())
}

func (s *Server) mountMistyRoutes(prefix string, aiService *api.AIService) {
	s.Router.Get(prefix+"/misty/events", aiService.AccountEvents())
	s.Router.Post(prefix+"/misty/agent-followup", aiService.AgentFollowup())
	s.Router.Post(prefix+"/misty/agent-execution", aiService.AgentExecutionLease())
	s.Router.Delete(prefix+"/misty/agent-execution/{taskID}", aiService.AgentExecutionLease())
	s.Router.Get(prefix+"/misty/agents", aiService.PersonalAgents())
	s.Router.Post(prefix+"/misty/agents", aiService.PersonalAgents())
	s.Router.Put(prefix+"/misty/agents/{agentID}", aiService.PersonalAgent())
	s.Router.Delete(prefix+"/misty/agents/{agentID}", aiService.PersonalAgent())
	s.Router.MethodFunc(http.MethodGet, prefix+"/misty/conversations", aiService.MistyConversations())
	s.Router.MethodFunc(http.MethodPost, prefix+"/misty/conversations", aiService.MistyConversations())
	s.Router.MethodFunc(http.MethodDelete, prefix+"/misty/conversations/{conversationID}", aiService.MistyConversation())
	s.Router.MethodFunc(http.MethodPatch, prefix+"/misty/conversations/{conversationID}", aiService.MistyConversation())
	s.Router.MethodFunc(http.MethodGet, prefix+"/misty/onboarding", aiService.AgentOnboarding())
	s.Router.MethodFunc(http.MethodGet, prefix+"/misty/conversation-folders", aiService.MistyConversationFolders())
	s.Router.MethodFunc(http.MethodPost, prefix+"/misty/conversation-folders", aiService.MistyConversationFolders())
	s.Router.MethodFunc(http.MethodPatch, prefix+"/misty/conversation-folders/{folderID}", aiService.MistyConversationFolder())
	s.Router.MethodFunc(http.MethodDelete, prefix+"/misty/conversation-folders/{folderID}", aiService.MistyConversationFolder())
	s.Router.MethodFunc(http.MethodPost, prefix+"/misty/attachments", aiService.MistyAttachments())
	s.Router.MethodFunc(http.MethodPost, prefix+"/misty/attachments/{attachmentID}/finalize", aiService.MistyAttachment())
	s.Router.MethodFunc(http.MethodDelete, prefix+"/misty/attachments/{attachmentID}", aiService.MistyAttachment())
	s.Router.MethodFunc(http.MethodGet, prefix+"/misty/attachments/{attachmentID}/content", aiService.MistyAttachmentContent())
	s.Router.MethodFunc(http.MethodPut, prefix+"/misty/attachments/{attachmentID}/content", aiService.MistyAttachmentContent())
}
