import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../../", import.meta.url));
const target = path.join(root, "apps/api/src/modules/official-apps/catalog.generated.ts");
const check = process.argv.includes("--check");
let document;
if (check) {
  // Temporary parity gate while Go is deployed; the native build/runtime never reads Go.
  const go = await readFile(path.join(root, "internal/appcatalog/catalog.go"), "utf8");
  const match = /const generatedCatalog = `([\s\S]*?)`/.exec(go);
  if (!match) throw new Error("Cannot read deployed Go catalog for parity verification");
  document = JSON.parse(match[1]);
} else {
  const source = process.argv[2];
  if (!source) throw new Error("Pass the reviewed misty-apps/apps/catalog.json source path");
  document = JSON.parse(await readFile(path.resolve(source), "utf8"));
}
if (document.schema_version !== 1 || !Array.isArray(document.apps)) throw new Error("Invalid catalog document");
const generated = `// Generated by scripts/migration/sync-app-catalog.mjs from the reviewed Store catalog.\n// Do not edit this snapshot by hand.\nexport const catalogDocument = ${JSON.stringify(document, null, 2)} as const;\n`;
if (check) {
  if (await readFile(target, "utf8") !== generated) throw new Error("Native official-app catalog differs from the deployed Go catalog; synchronize both from the reviewed Store release");
  process.stdout.write(`${document.apps.length} official apps match the deployed catalog.\n`);
} else {
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, generated);
  process.stdout.write(`Snapshotted ${document.apps.length} official apps for the native API.\n`);
}
