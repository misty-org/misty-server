package main

import (
	"strconv"

	"github.com/misty-org/misty-server/internal/platform/serverenv"
)

// The stack stores one secret of its own, the root (MISTY_SERVER_SECRET).
// Every other key is derived from it (serverenv.Keys) with a version per key
// kept in state.json, so one key rotates by moving to its next version. A
// value stored under a key's own name wins over the derived one: a secrets
// volume from before the root keeps its keys until the operator moves them
// (rotate, or adopt-root).

// secretSpec is one key and what may happen to it.
type secretSpec struct {
	serverenv.Key
	// DataBound keys protect data already written: a new value would make
	// that data unreadable, so they are never rotated, and a stack whose
	// database holds data refuses to start without them.
	DataBound bool
	// Guarded keys are needed to reach the data (the database superuser
	// password): a stack with data refuses to start without them, but they
	// rotate through their previous slot.
	Guarded bool
	// Rotatable without a previous slot: the new value takes effect when the
	// stack restarts.
	Rotatable bool
}

var secretSpecs = []secretSpec{
	{Key: key("DB_MIGRATION_PASSWORD"), Guarded: true},
	{Key: key("DB_PASSWORD"), Rotatable: true},
	{Key: key("MISTY_AUTH_SIGNING_KEY")},
	{Key: key("MISTY_OPERATOR_TOKEN")},
	{Key: key("MISTY_METRICS_TOKEN"), Rotatable: true},
	{Key: key("SPACE_LINK_ENCRYPTION_KEY"), DataBound: true},
	{Key: key("JOURNAL_COLLAB_TICKET_PRIVATE_KEY")},
	{Key: key("JOURNAL_COLLAB_CONTROL_SECRET")},
	{Key: key("JOURNAL_COLLAB_PROJECTION_SECRET")},
	{Key: key("JOURNAL_COLLAB_ROOM_SALT"), DataBound: true},
	{Key: key("MISTY_BACKUP_AGE_IDENTITY"), DataBound: true},
}

// retiredSecrets were generated by earlier versions and are no longer read
// by a stack setup manages. adopt-root drops them.
var retiredSecrets = []string{
	// The API reads it only when SPACE_LINK_ENCRYPTION_KEY is unset, which
	// never happens on a stack setup manages.
	"DOCUMENT_SIGNING_KEY",
}

func key(name string) serverenv.Key {
	found, ok := serverenv.Lookup(name)
	if !ok {
		panic("unknown key " + name)
	}
	return found
}

func specFor(name string) (secretSpec, bool) {
	for _, spec := range secretSpecs {
		if spec.Name == name {
			return spec, true
		}
	}
	return secretSpec{}, false
}

// specForPrevious finds the key whose previous slot is name.
func specForPrevious(name string) (secretSpec, bool) {
	for _, spec := range secretSpecs {
		if spec.Previous != "" && spec.Previous == name {
			return spec, true
		}
	}
	return secretSpec{}, false
}

// State entries for each key: its version, the previous version still
// accepted, and for the keys that guard data whether it is the stored value
// or the root's.
func versionState(purpose string) string  { return "key:" + purpose + ":version" }
func previousState(purpose string) string { return "key:" + purpose + ":previous" }
func sourceState(purpose string) string   { return "key:" + purpose + ":source" }

const (
	sourceStored = "stored"
	sourceRoot   = "root"
)

func (s *Store) version(purpose string) serverenv.Version {
	current, _ := strconv.Atoi(s.State[versionState(purpose)])
	previous, _ := strconv.Atoi(s.State[previousState(purpose)])
	if current < 1 {
		current = 1
	}
	if previous >= current {
		previous = 0
	}
	return serverenv.Version{Current: current, Previous: previous}
}

func (s *Store) setVersion(purpose string, version serverenv.Version) {
	delete(s.State, versionState(purpose))
	delete(s.State, previousState(purpose))
	if version.Current > 1 {
		s.State[versionState(purpose)] = strconv.Itoa(version.Current)
	}
	if version.Previous > 0 {
		s.State[previousState(purpose)] = strconv.Itoa(version.Previous)
	}
}

// versions are every key's version, as the API reads them.
func (s *Store) versions() serverenv.Versions {
	versions := serverenv.Versions{}
	for _, spec := range secretSpecs {
		versions[spec.Purpose] = s.version(spec.Purpose)
	}
	return versions
}

// root is the decoded root secret, or nil before setup made one.
func (s *Store) root() []byte {
	encoded := s.Values[serverenv.RootName]
	if encoded == "" {
		return nil
	}
	root, err := serverenv.DecodeSecret(serverenv.RootName, encoded)
	if err != nil {
		return nil
	}
	return root
}

// derived is the value the root gives a name: a key at its current version,
// a previous slot at its previous version, or a value that follows from
// those. It is "" when the root gives the name nothing.
func (s *Store) derived(name string) string {
	root := s.root()
	if root == nil {
		return ""
	}
	value, err := s.deriveFrom(root, name)
	if err != nil {
		return ""
	}
	return value
}

func (s *Store) deriveFrom(root []byte, name string) (string, error) {
	switch name {
	case serverenv.APISecretName:
		return serverenv.APISecret(root)
	case serverenv.VersionsName:
		return s.versions().String(), nil
	}
	if spec, ok := specFor(name); ok {
		source, err := spec.Source(root)
		if err != nil {
			return "", err
		}
		return spec.Value(source, s.version(spec.Purpose).Current)
	}
	if spec, ok := specForPrevious(name); ok {
		previous := s.version(spec.Purpose).Previous
		if previous == 0 {
			return "", nil
		}
		source, err := spec.Source(root)
		if err != nil {
			return "", err
		}
		return spec.PreviousValue(source, previous)
	}
	return "", nil
}

// computedValues follow from other values and are never stored; volumes from
// earlier versions hold them, so openStore drops them. The API works out the
// public URL and the Library bucket from MISTY_HOSTNAME, setup the backup
// bucket the same way; the tunnel ID moves into state.json; the API secret
// and the versions are rendered into server.env on every save.
var computedValues = []string{
	"JOURNAL_COLLAB_TICKET_PUBLIC_KEY", "MISTY_BACKUP_AGE_RECIPIENT",
	"MISTY_PUBLIC_API_URL", "R2_BUCKET", "MISTY_BACKUP_BUCKET", "MISTY_CLOUDFLARE_TUNNEL_ID",
	serverenv.APISecretName, serverenv.VersionsName,
}

// computed is a value that follows from another one, or "".
func (s *Store) computed(name string) string {
	switch name {
	case "JOURNAL_COLLAB_TICKET_PUBLIC_KEY":
		public, _ := serverenv.Ed25519PublicKey(s.Get("JOURNAL_COLLAB_TICKET_PRIVATE_KEY"))
		return public
	case "MISTY_BACKUP_AGE_RECIPIENT":
		recipient, _ := serverenv.AgeRecipient(s.Get("MISTY_BACKUP_AGE_IDENTITY"))
		return recipient
	}
	return ""
}

// normalize turns a volume from an earlier version into this one's layout:
// computed values leave server.env (the tunnel ID moves into state.json), and
// a stored key equal to what the root derives is the derived one.
func (s *Store) normalize() {
	if id := s.Values["MISTY_CLOUDFLARE_TUNNEL_ID"]; id != "" && s.State[tunnelState] == "" {
		s.State[tunnelState] = id
	}
	for _, name := range computedValues {
		delete(s.Values, name)
	}
	for _, spec := range secretSpecs {
		for _, name := range []string{spec.Name, spec.Previous} {
			if name != "" && s.Values[name] != "" && s.Values[name] == s.derived(name) {
				delete(s.Values, name)
			}
		}
	}
}
