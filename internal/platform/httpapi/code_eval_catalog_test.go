package api

import (
	"bytes"
	"encoding/json"
	"os"
	"strings"
	"testing"
)

// The code eval (server/apps/agent-runtime/evals/code) gives a model the same
// code tools, descriptions and guidance a desktop chat with one project gets.
// This test keeps its catalog current; regenerate it with
//
//	MISTY_WRITE_CODE_EVAL_CATALOG=1 go test ./internal/platform/httpapi -run TestCodeEvalCatalogIsCurrent
const codeEvalCatalogPath = "../../../apps/agent-runtime/evals/code/catalog.json"

func codeEvalCatalog(t *testing.T) []byte {
	t.Helper()
	var service SpacesService
	tools := []map[string]any{}
	names := []string{}
	for _, registration := range service.projectToolRegistrations([]deviceGrant{{scopeID: "scope_eval", name: "site", deviceID: "device-eval"}}) {
		descriptor := registration.Descriptor
		var schema any
		if err := json.Unmarshal(descriptor.InputSchema, &schema); err != nil {
			t.Fatal(err)
		}
		names = append(names, descriptor.Name)
		tools = append(tools, map[string]any{
			"name": descriptor.Name, "description": descriptor.Description, "inputSchema": schema,
			"readOnly": descriptor.Risk == "read",
		})
	}
	out, err := json.MarshalIndent(map[string]any{
		"note":     "Generated by server/internal/platform/httpapi/code_eval_catalog_test.go. Do not edit.",
		"tools":    tools,
		"guidance": strings.TrimSpace(agentCapabilityGuidance(names, false)),
	}, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	return append(out, '\n')
}

func TestCodeEvalCatalogIsCurrent(t *testing.T) {
	want := codeEvalCatalog(t)
	if os.Getenv("MISTY_WRITE_CODE_EVAL_CATALOG") == "1" {
		if err := os.WriteFile(codeEvalCatalogPath, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(codeEvalCatalogPath)
	if err != nil {
		t.Fatalf("read %s: %v (regenerate with MISTY_WRITE_CODE_EVAL_CATALOG=1)", codeEvalCatalogPath, err)
	}
	// A Windows checkout may store the catalog with CRLF line endings.
	if !bytes.Equal(bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n")), want) {
		t.Fatal("the code eval catalog is stale; regenerate it with MISTY_WRITE_CODE_EVAL_CATALOG=1")
	}
}
