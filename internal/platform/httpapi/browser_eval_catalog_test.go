package api

import (
	"bytes"
	"encoding/json"
	"os"
	"strings"
	"testing"
)

// The browser eval (server/apps/agent-runtime/evals/browser) gives a model the
// same browser tools, descriptions and guidance production runs get. This test
// keeps its catalog current; regenerate it with
//
//	MISTY_WRITE_BROWSER_EVAL_CATALOG=1 go test ./internal/platform/httpapi -run TestBrowserEvalCatalogIsCurrent
const browserEvalCatalogPath = "../../../apps/agent-runtime/evals/browser/catalog.json"

// The tools an attached Misty browser tab offers, minus browser_act (its screen
// agent runs on the desktop) and the file tools (no conversation attachments).
var browserEvalTools = []string{
	"browser.navigate", "browser.snapshot", "browser.find", "browser.extract", "browser.wait_for",
	"browser.steps", "browser.fill_form", "browser.skill", "browser.request_user_action",
}

func browserEvalCatalog(t *testing.T) []byte {
	t.Helper()
	byName := map[string]map[string]any{}
	for _, descriptor := range browserToolDescriptors() {
		var schema any
		if err := json.Unmarshal(descriptor.InputSchema, &schema); err != nil {
			t.Fatal(err)
		}
		byName[descriptor.Name] = map[string]any{
			"name": descriptor.Name, "description": descriptor.Description, "inputSchema": schema,
			"readOnly": descriptor.Risk == "read",
		}
	}
	tools := make([]map[string]any, 0, len(browserEvalTools))
	for _, name := range browserEvalTools {
		tool, ok := byName[name]
		if !ok {
			t.Fatalf("browser eval tool %s is not in the catalog", name)
		}
		tools = append(tools, tool)
	}
	out, err := json.MarshalIndent(map[string]any{
		"note":     "Generated by server/internal/platform/httpapi/browser_eval_catalog_test.go. Do not edit.",
		"tools":    tools,
		"guidance": strings.TrimSpace(agentCapabilityGuidance(browserEvalTools, false)),
	}, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	return append(out, '\n')
}

func TestBrowserEvalCatalogIsCurrent(t *testing.T) {
	want := browserEvalCatalog(t)
	if os.Getenv("MISTY_WRITE_BROWSER_EVAL_CATALOG") == "1" {
		if err := os.WriteFile(browserEvalCatalogPath, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(browserEvalCatalogPath)
	if err != nil {
		t.Fatalf("read %s: %v (regenerate with MISTY_WRITE_BROWSER_EVAL_CATALOG=1)", browserEvalCatalogPath, err)
	}
	// A Windows checkout may store the catalog with CRLF line endings.
	if !bytes.Equal(bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n")), want) {
		t.Fatal("the browser eval catalog is stale; regenerate it with MISTY_WRITE_BROWSER_EVAL_CATALOG=1")
	}
}
